DEEP, FRESH_MIN, UNEXPLORED_MAX = 300, 25, 20


def compile_rules(cats: dict):
    return None  # kept for compatibility: patterns now live in lib.category_patterns()


def classify(text: str, rules=None) -> str:
    return lib.classify_category(text)


def suggest(known: int, emailed: int, fresh: int, campaigns: int, excluded: bool, proposed: bool = False, slug: str = "") -> str:
    if slug == "other_unclassified":
        return "needs classification"
    if excluded:
        return "not a target"
    if proposed and emailed == 0:
        return "proposed, not searched yet"
    if emailed == 0 and known < UNEXPLORED_MAX and campaigns == 0:
        return "unexplored"
    if fresh < FRESH_MIN and emailed >= 100:
        return "exhausted by our sweeps"
    if emailed >= DEEP and fresh >= FRESH_MIN:
        return "explored, some fresh left"
    if emailed == 0:
        return "found, never contacted"
    return "partly explored"


def pipeline_stages(conn, cats: dict) -> dict:
    """Counts per category for businesses researched by this system (origin gosom): where they are in the pipeline."""
    out = collections.defaultdict(collections.Counter)
    hint = {r["business_id"]: r["value"] for r in conn.execute("SELECT business_id, value FROM evidence WHERE field='category_hint'")}
    ready = {r["business_id"] for r in conn.execute("SELECT business_id FROM checks WHERE passed=1")}
    tier = {r["business_id"]: r["tier"] for r in conn.execute("SELECT business_id, tier FROM scores")}
    for b in conn.execute("SELECT id, status, segment, origin FROM businesses WHERE origin='gosom'"):
        slug = hint.get(b["id"]) if hint.get(b["id"]) in cats else b["segment"]  # the category we SEARCHED for (a site can read as another segment)
        if slug not in cats:
            continue
        o = out[slug]
        o["found"] += 1
        o[b["status"]] += 1
        if b["id"] in ready and b["status"] == "verified":
            o["ready_to_load"] += 1
            o["ready_" + tier.get(b["id"], "?")] += 1
    return out


def write_state(conn, rows, cats, groups):
    """CATEGORY_STATE.md at the repo root: counts only (no emails), safe for a public repo. Committed by `run.py save`."""
    stages = pipeline_stages(conn, cats)
    log = collections.defaultdict(lambda: {"n": 0, "read": 0, "new": 0, "last": ""})
    for r in conn.execute("SELECT category, COUNT(*) n, SUM(rows_read) rd, SUM(rows_new) nw, MAX(ran_at) last FROM search_log GROUP BY category"):
        log[r["category"]] = {"n": r["n"], "read": r["rd"] or 0, "new": r["nw"] or 0, "last": (r["last"] or "")[:10]}
    n_cities = len(lib.load_yaml("segments.yaml")["launch_cities"])
    by = {r["category"]: r for r in rows}
    L = ["# Category state (generated by `python pipeline/category_report.py`, do not edit by hand)", "",
         f"Generated {lib.now()} UTC. Counts only, no personal data. Source of truth for what is consumed and what is still contactable.", "",
         "## How another session continues", "",
         "1. `git pull`, `python run.py restore` (if `data/tryuu.db` is missing), `python run.py status`.",
         "2. Pick a category from **Contactable now** or **Not searched yet**. Never re-run a query already listed in **Searches run**:",
         "   `discover_batch.py` skips them by itself (`search_log` table).",
         "3. Discover: `python pipeline/discover_batch.py <category>` (Docker must be up: `setsid nohup dockerd`). Standing rule: it searches every city AND every neighbourhood of the 15 launch cities (265 areas, see CLAUDE.md); a category is only 'consumed' when both passes are logged.",
         "4. `python run.py research`; answer the extraction worksheet (`llm.py export ... --kind extract`, `llm.py import`), re-run it; same for `segment_check`.",
         "5. Ready leads = status `verified` with a passed check. Loading needs the owner's approved copy and campaign id (see CLAUDE.md). Never activate campaigns.",
         "6. `python pipeline/category_report.py` then `python run.py save \"...\"` so this file stays current.", "",
         "## Contactable now (researched by this system, not yet emailed)", "",
         "| Category | Found | Enriched | Scored A/B | Verified | Ready to load | Loaded/sent | Searches run |", "|---|---|---|---|---|---|---|---|"]
    any_row = False
    for slug in cats:
        s = stages.get(slug)
        if not s:
            continue
        any_row = True
        lg = log[slug]
        L.append(f"| {slug} | {s['found']} | {s['enriched']} | {s['scored']} | {s['verified']} | **{s['ready_to_load']}** (A {s['ready_A']}, B {s['ready_B']}) | {s['loaded'] + s['sent'] + s['replied']} | {lg['n']} |")
    if not any_row:
        L.append("| (none yet) | | | | | | | |")
    L += ["", "## Contactable from the legacy pool (never emailed, discovered before this system)", "", "| Category | Never contacted | Known | Emailed |", "|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["fresh_legacy"]):
        if r["fresh_legacy"] >= 5 and r["status"] not in ("not a target", "needs classification"):
            L.append(f"| {r['category']} | {r['fresh_legacy']} | {r['known']} | {r['emailed']} |")
    L += ["", "## Consumed (exhausted by our sweeps: fewer than 25 never contacted and 100+ emailed)", "",
          "Re-entry is possible 60 days after the last email (cooldown in `config/suppression_seed.yaml`), with the new sequence.", "",
          "| Category | Known | Emailed | Live | Legacy campaigns |", "|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["emailed"]):
        if r["status"] == "exhausted by our sweeps":
            L.append(f"| {r['category']} | {r['known']} | {r['emailed']} | {r['live']} | {r['legacy_campaigns']} |")
    L += ["", "## Searches run by this system (discovery queries)", "", f"A category is fully searched when queries = keywords x {n_cities} launch cities.", "",
          "| Category | Queries run | Places read | New to us | Last run |", "|---|---|---|---|---|"]
    for slug in cats:
        lg = log.get(slug)
        if lg and lg["n"]:
            L.append(f"| {slug} | {lg['n']} | {lg['read']} | {lg['new']} | {lg['last']} |")
    L += ["", "## Not searched yet (proposed)", ""] + [f"- `{r['category']}`: {cats[r['category']]['noun']}" + (f" ({cats[r['category']]['track']})" if cats[r['category']].get('track') else "")
                                                  for r in rows if r["status"] == "proposed, not searched yet" and not log.get(r["category"], {"n": 0})["n"]]
    L += ["", "## Partly explored (a deeper search is still possible)", ""] + [f"- `{r['category']}`: known {r['known']}, emailed {r['emailed']}, never contacted {r['fresh_never_contacted']}"
                                                                         for r in rows if r["status"] in ("partly explored", "explored, some fresh left", "found, never contacted")]
    (lib.ROOT / "CATEGORY_STATE.md").write_text("\n".join(L) + "\n")


def main():
    conn = lib.connect()
    cfg = lib.load_yaml("categories.yaml")
    cats, groups = cfg["categories"], cfg["groups"]
    rules = compile_rules(cats)
    types = {r["business_id"]: r["value"] for r in conn.execute("SELECT business_id, value FROM evidence WHERE field='legacy_business_type'")}
    seg = {r["business_id"]: r["value"] for r in conn.execute("SELECT business_id, value FROM evidence WHERE field='segment'")}
    hints = {r["business_id"]: r["value"] for r in conn.execute("SELECT business_id, value FROM evidence WHERE field='category_hint'")}
    onboard_ids = {r["business_id"] for r in conn.execute("SELECT business_id FROM onboarded WHERE business_id IS NOT NULL")}
    interested = {r["business_id"] for r in conn.execute("SELECT business_id FROM evidence WHERE field='instantly_interest' AND value='1'")}
    bounced = {r["business_id"] for r in conn.execute("SELECT DISTINCT business_id FROM sends WHERE bounced=1 AND business_id IS NOT NULL")}
    stat = collections.defaultdict(lambda: collections.Counter())
    unclassified = collections.Counter()
    for b in conn.execute("SELECT id, status, origin FROM businesses"):
        text = types.get(b["id"]) or seg.get(b["id"]) or ""
        slug = seg[b["id"]] if seg.get(b["id"]) in cats else classify(text, rules) if text else hints.get(b["id"], "other_unclassified")
        if slug not in cats:
            slug = "other_unclassified"
        if slug == "other_unclassified" and text:
            unclassified[text.lower()] += 1
        s = stat[slug]
        s["known"] += 1
        s[b["status"]] += 1
        if b["origin"] != "gosom" and b["status"] in ("discovered", "enriched", "scored", "verified"):
            s["fresh_legacy"] += 1
        if b["status"] in ("sent", "replied", "loaded", "onboarded"):
            s["emailed"] += 1
        if b["id"] in onboard_ids or b["status"] == "onboarded":
            s["live"] += 1
        s["interested"] += b["id"] in interested
        s["bounced"] += b["id"] in bounced
    rows = []
    for slug, c in cats.items():
        s = stat.get(slug, collections.Counter())
        emailed, fresh = s["emailed"], s["discovered"] + s["enriched"] + s["scored"] + s["verified"]
        rows.append({
            "category": slug, "group": c["group"], "known": s["known"], "emailed": emailed, "fresh_never_contacted": fresh, "fresh_legacy": s["fresh_legacy"],
            "replied": s["replied"], "interested": s["interested"], "live": s["live"], "bounced": s["bounced"],
            "live_per_1000_emailed": round(1000 * s["live"] / emailed, 1) if emailed else "",
            "legacy_campaigns": " ".join(map(str, c.get("campaigns", []))), "proven": bool(c.get("proven")),
            "status": suggest(s["known"], emailed, fresh, len(c.get("campaigns", [])), bool(c.get("excluded")), bool(c.get("proposed")), slug)})
    out = lib.ROOT / "reports"
    out.mkdir(exist_ok=True)
    with (out / "category_coverage.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    lines = ["# Category coverage", "", "| group | category | known | emailed | fresh | live | live/1000 | interested | status |", "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["group"], -r["known"])):
        lines.append(f"| {groups[r['group']]} | {r['category']} | {r['known']} | {r['emailed']} | {r['fresh_never_contacted']} | {r['live']} | {r['live_per_1000_emailed']} | {r['interested']} | {r['status']} |")
    lines += ["", "## Top unclassified types (add tokens to config/categories.yaml)", ""] + [f"- {t}: {n}" for t, n in unclassified.most_common(40)]
    (out / "category_coverage.md").write_text("\n".join(lines) + "\n")
    write_state(conn, rows, cats, groups)
    print("\n".join(lines[:4 + len(rows)]))
    print(f"\nunclassified businesses with a type: {sum(unclassified.values())}; without any type: {stat['other_unclassified']['known'] - sum(unclassified.values())}")
    print("top unclassified:", "; ".join(f"{t}={n}" for t, n in unclassified.most_common(30)))


if __name__ == "__main__":
    main()
